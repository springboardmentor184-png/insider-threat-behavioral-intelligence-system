def get_device_analysis(
    db: Session,
    investigation_id: int
):
    """
    Return device usage analysis for
    an investigation.
    """

    investigation = (
        db.query(Investigation)
        .filter(
            Investigation.id == investigation_id
        )
        .first()
    )

    if not investigation:
        return None

    log = (
        db.query(BehaviorLog)
        .filter(
            BehaviorLog.employee_id == investigation.employee_id
        )
        .first()
    )

    if not log:
        return None

    # Calculate Device Risk
    if (
        log.usb_used
        and log.after_hours_login
        and log.files_downloaded >= 400
    ):

        device_risk = "High"

    elif (
        log.usb_used
        or log.after_hours_login
    ):

        device_risk = "Medium"

    else:

        device_risk = "Low"

    return {

        "login_hour": log.login_hour,

        "usb_used": log.usb_used,

        "after_hours_login": log.after_hours_login,

        "files_downloaded": log.files_downloaded,

        "emails_sent": log.emails_sent,

        "device_risk": device_risk

    }

