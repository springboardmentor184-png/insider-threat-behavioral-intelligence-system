# Investigation Workflow
# =====================================================

def update_investigation_workflow(
    db: Session,
    investigation_id: int,
    workflow
):
    """
    Update investigation workflow.
    """

    investigation = (
        db.query(Investigation)
        .filter(
            Investigation.id == investigation_id
        )
        .first()
    )

    if not investigation:
        return None

    investigation.assigned_analyst = workflow.assigned_analyst

    investigation.status = workflow.status

    investigation.investigation_notes = workflow.investigation_notes

    investigation.recommendation = workflow.recommendation

    db.commit()

    db.refresh(investigation)

    return {

        "message": "Investigation updated successfully",

        "investigation_id": investigation.id,

        "assigned_analyst": investigation.assigned_analyst,

        "status": investigation.status

    }