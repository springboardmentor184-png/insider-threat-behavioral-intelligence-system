# Threat Evidence Collection
# =====================================================

def get_threat_evidence(
    db: Session,
    investigation_id: int
):
    """
    Return all evidence that triggered
    the threat investigation.
    """

    investigation = (
        db.query(Investigation)
        .filter(
            Investigation.id == investigation_id
        )
        .first()
    )

    if not investigation:
        return None

    log = (
        db.query(BehaviorLog)
        .filter(
            BehaviorLog.employee_id == investigation.employee_id
        )
        .first()
    )

    if not log:
        return None

    # Determine Detection Method
    if investigation.threat_severity in [
        "High",
        "Critical"
    ]:
        detection_method = "Hybrid Rule Engine"

    else:
        detection_method = "Isolation Forest"

    return {

        "failed_logins": log.failed_logins,

        "files_downloaded": log.files_downloaded,

        "emails_sent": log.emails_sent,

        "usb_used": log.usb_used,

        "after_hours_login": log.after_hours_login,

        "risk_level": investigation.threat_severity,

        "detection_method": detection_method

    }

