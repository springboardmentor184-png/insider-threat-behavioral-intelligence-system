# Event Correlation
# =====================================================

def get_event_correlation(
    db: Session,
    investigation_id: int
):
    """
    Correlate suspicious behaviour events
    for an investigation.
    """

    investigation = (
        db.query(Investigation)
        .filter(
            Investigation.id == investigation_id
        )
        .first()
    )

    if not investigation:
        return None

    employee = (
        db.query(Employee)
        .filter(
            Employee.id == investigation.employee_id
        )
        .first()
    )

    log = (
        db.query(BehaviorLog)
        .filter(
            BehaviorLog.employee_id == employee.id
        )
        .order_by(
            BehaviorLog.created_at.desc()
        )
        .first()
    )

    if not log:
        return None

    events = []

    score = 0

    if log.failed_logins >= 5:

        events.append({
            "event": "Multiple Failed Login Attempts",
            "severity": "High",
            "correlated": True
        })

        score += 20

    if log.usb_used:

        events.append({
            "event": "USB Device Connected",
            "severity": "High",
            "correlated": True
        })

        score += 20

    if log.files_downloaded >= 100:

        events.append({
            "event": "Mass File Download",
            "severity": "High",
            "correlated": True
        })

        score += 20

    if log.emails_sent >= 50:

        events.append({
            "event": "Bulk Email Activity",
            "severity": "Medium",
            "correlated": True
        })

        score += 20

    if log.after_hours_login:

        events.append({
            "event": "After Hours Login",
            "severity": "High",
            "correlated": True
        })

        score += 20

    return {

        "employee_name": employee.full_name,

        "total_events": len(events),

        "risk_level": investigation.threat_severity,

        "correlation_score": score,

        "events": events

    }

