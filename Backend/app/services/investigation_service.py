# User Risk History
# =====================================================

def get_user_risk_history(
    db: Session,
    investigation_id: int
):
    """
    Return historical risk profile for
    an investigated employee.
    """

    investigation = (
        db.query(Investigation)
        .filter(
            Investigation.id == investigation_id
        )
        .first()
    )

    if not investigation:
        return None

    employee = (
        db.query(Employee)
        .filter(
            Employee.id == investigation.employee_id
        )
        .first()
    )

    if not employee:
        return None

    investigations = (
        db.query(Investigation)
        .filter(
            Investigation.employee_id == employee.id
        )
        .all()
    )

    total_incidents = len(investigations)

    current_risk = investigation.threat_severity

    if total_incidents > 1:
        previous_risk = investigations[-2].threat_severity
    else:
        previous_risk = "None"

    # Approximate score from severity
    score_map = {
        "Low": 25,
        "Medium": 50,
        "High": 75,
        "Critical": 100
    }

    scores = [
        score_map.get(i.threat_severity, 25)
        for i in investigations
    ]

    average_risk_score = (
        int(sum(scores) / len(scores))
        if scores else 0
    )

    # Behaviour trend
    if current_risk == "Critical":
        trend = "Increasing"

    elif current_risk == "High":
        trend = "Elevated"

    else:
        trend = "Stable"

    return {

        "employee_name": employee.full_name,

        "current_risk": current_risk,

        "previous_risk": previous_risk,

        "total_incidents": total_incidents,

        "average_risk_score": average_risk_score,

        "behaviour_trend": trend

    }

