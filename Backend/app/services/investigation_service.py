# =====================================================
# Automatic Investigation Generation
# =====================================================

def generate_investigation(
    db: Session,
    employee_id: int,
    prediction: dict
):
    """
    Automatically create investigation for
    High/Critical insider threats.
    """

    if prediction["risk_level"] not in [
        "High",
        "Critical"
    ]:
        return None

    existing = (
        db.query(Investigation)
        .filter(
            Investigation.employee_id == employee_id,
            Investigation.status != "Closed"
        )
        .first()
    )

    if existing:
        return existing

    investigation = Investigation(

        employee_id=employee_id,

        incident_title="Potential Insider Threat Detected",

        threat_severity=prediction["threat_severity"],

        status="Open",

        assigned_analyst="Unassigned",

        investigation_notes="Automatically generated by AI Threat Detection Engine.",

        recommendation=prediction["recommendation"]

    )

    db.add(investigation)
    db.commit()
    db.refresh(investigation)

    return investigation


